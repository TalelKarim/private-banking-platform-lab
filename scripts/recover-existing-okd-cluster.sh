#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
RUNTIME_ROOT=${OKD_RUNTIME_ROOT:-$ROOT_DIR/.runtime/openshift}
TF_STATE="$RUNTIME_ROOT/terraform-nodes/terraform.tfstate"
TF_VARS="$RUNTIME_ROOT/terraform-nodes/runtime.auto.tfvars.json"
INSTALL_DIR="$RUNTIME_ROOT/install"
CANONICAL_KUBECONFIG="$INSTALL_DIR/auth/kubeconfig"
RECOVERED_DIR="$RUNTIME_ROOT/recovered"
RECOVERED_KUBECONFIG="$RECOVERED_DIR/kubeconfig"
READY_MARKER="$RUNTIME_ROOT/existing-cluster.ready"
CLUSTER_CONFIG="$ROOT_DIR/platform/openshift/cluster-config.yml"
RECOVERY_KUBECONFIG_PATH=/etc/kubernetes/static-pod-resources/kube-apiserver-certs/secrets/node-kubeconfigs/localhost-recovery.kubeconfig
ANSIBLE_PYTHON=${ANSIBLE_PYTHON:-/opt/ansible-venv/bin/python}

for binary in oc jq ssh; do
  command -v "$binary" >/dev/null 2>&1 || {
    echo "Required command not found: $binary" >&2
    exit 1
  }
done

[[ -x "$ANSIBLE_PYTHON" ]] || {
  echo "Missing Python from Ansible environment: $ANSIBLE_PYTHON" >&2
  exit 1
}

read -r OKD_CLUSTER_NAME OKD_BASE_DOMAIN < <(
  "$ANSIBLE_PYTHON" - "$CLUSTER_CONFIG" <<'PY'
import sys
import yaml
with open(sys.argv[1], encoding="utf-8") as handle:
    cfg = yaml.safe_load(handle)
print(cfg["okd_cluster_name"], cfg["okd_base_domain"])
PY
)
API_URL="https://api.$OKD_CLUSTER_NAME.$OKD_BASE_DOMAIN:6443"

if [[ ! -s "$TF_STATE" || ! -s "$TF_VARS" ]]; then
  echo "Existing OKD cluster detected, but runtime Terraform state/variables are missing." >&2
  echo "Run: make recover-okd-runtime-state" >&2
  exit 1
fi

if [[ "$(jq -r 'if has("bootstrap_enabled") then .bootstrap_enabled else true end' "$TF_VARS")" != false ]]; then
  echo "Existing OKD cluster is not marked bootstrap_enabled=false in runtime Terraform." >&2
  echo "Run: make recover-okd-runtime-state" >&2
  exit 1
fi

state_has_control_plane() {
  local name=$1
  jq -e --arg name "$name" '
    any(.resources[]?;
      .type == "openstack_compute_instance_v2"
      and .name == "control_plane"
      and any(.instances[]?; .index_key == $name)
    )
    and
    any(.resources[]?;
      .type == "openstack_networking_port_v2"
      and .name == "control_plane"
      and any(.instances[]?; .index_key == $name)
    )
  ' "$TF_STATE" >/dev/null
}

for node in okd-01 okd-02 okd-03; do
  if ! state_has_control_plane "$node"; then
    echo "Runtime Terraform state does not manage $node and its Neutron port." >&2
    echo "Run: make recover-okd-runtime-state" >&2
    exit 1
  fi
done

if jq -e '
  any(.resources[]?;
    (.name == "bootstrap")
    and ((.type == "openstack_compute_instance_v2") or (.type == "openstack_networking_port_v2"))
    and ((.instances // []) | length > 0)
  )
' "$TF_STATE" >/dev/null; then
  echo "Bootstrap resources are still present in runtime Terraform state." >&2
  echo "Run: make recover-okd-runtime-state" >&2
  exit 1
fi

install -d -m 0700 "$RECOVERED_DIR"
install -d -m 0700 "$INSTALL_DIR/auth"
TMP_KUBECONFIG=$(mktemp "$RECOVERED_DIR/kubeconfig.XXXXXX")
trap 'rm -f "$TMP_KUBECONFIG"' EXIT

recovery_source=
for node in okd-01 okd-02 okd-03; do
  if ssh -o BatchMode=yes -o ConnectTimeout=8 "$node"       "sudo cat '$RECOVERY_KUBECONFIG_PATH'" > "$TMP_KUBECONFIG" 2>/dev/null       && [[ -s "$TMP_KUBECONFIG" ]]; then
    recovery_source=$node
    break
  fi
done

if [[ -z "$recovery_source" ]]; then
  echo "Unable to recover an administrative kubeconfig from any existing control plane." >&2
  exit 1
fi

chmod 0600 "$TMP_KUBECONFIG"
context_cluster=$(oc --kubeconfig="$TMP_KUBECONFIG" config view   -o jsonpath='{.contexts[0].context.cluster}')
if [[ -z "$context_cluster" ]]; then
  echo "Recovered kubeconfig has no cluster context." >&2
  exit 1
fi

oc --kubeconfig="$TMP_KUBECONFIG" config set-cluster "$context_cluster"   --server="$API_URL" >/dev/null

NODE_JSON=$(oc --kubeconfig="$TMP_KUBECONFIG" get nodes -o json)
if ! jq -e '
  ([.items[].metadata.name] | sort) == ["okd-01","okd-02","okd-03"]
  and all(.items[];
    any(.status.conditions[]?; .type == "Ready" and .status == "True")
  )
' <<<"$NODE_JSON" >/dev/null; then
  echo "Recovered kubeconfig does not resolve to the expected healthy 3-node compact cluster." >&2
  oc --kubeconfig="$TMP_KUBECONFIG" get nodes -o wide >&2 || true
  exit 1
fi

install -m 0600 "$TMP_KUBECONFIG" "$RECOVERED_KUBECONFIG"
install -m 0600 "$TMP_KUBECONFIG" "$CANONICAL_KUBECONFIG"

# Assets generated by the failed fresh-install attempt describe a different
# cluster identity. Keep the canonical kubeconfig only and remove the markers/
# password that could make those stale assets look reusable or valid.
rm -f "$RUNTIME_ROOT/install-assets.ready"
rm -f "$INSTALL_DIR/auth/kubeadmin-password"

cat > "$READY_MARKER" <<EOF
mode=recovered-existing-cluster
source_node=$recovery_source
api=$API_URL
EOF
chmod 0600 "$READY_MARKER"

printf '%s\n' 'Existing OKD cluster access RECOVERED.'
printf '  source node : %s\n' "$recovery_source"
printf '  kubeconfig  : %s\n' "$CANONICAL_KUBECONFIG"
printf '  API         : %s\n' "$API_URL"
oc --kubeconfig="$CANONICAL_KUBECONFIG" get nodes
